    async def analyze_task(self, task: str) -> List[Dict[str, Any]]:
        """
        Analyze task and generate suggestions safely (optimized + production-grade)
        """

        suggestions: List[Dict[str, Any]] = []

        try:
            # ------------------------
            # 🔥 VALIDATION
            # ------------------------
            if not task or not isinstance(task, str):
                return []

            task = task.strip()
            if not task:
                return []

            # ------------------------
            # 🔁 TASK-BASED SUGGESTIONS
            # ------------------------
            try:
                task_suggestions = await self.generate_suggestions(task, limit=3)

                for s in task_suggestions or []:
                    try:
                        if hasattr(s, "to_dict"):
                            data = s.to_dict()
                        elif isinstance(s, dict):
                            data = s
                        else:
                            continue

                        # deduplicate by title
                        if not any(
                            existing.get("title") == data.get("title")
                            for existing in suggestions
                        ):
                            suggestions.append(data)

                    except Exception:
                        continue

            except Exception:
                pass

            # ------------------------
            # 🔥 EXPLORATION SUGGESTIONS
            # ------------------------
            try:
                queue = getattr(self, "queue", [])

                for item in queue[:2]:
                    if not hasattr(item, "topic"):
                        continue

                    title = f"Learn about {item.topic}"

                    # deduplicate
                    if any(s.get("title") == title for s in suggestions):
                        continue

                    suggestions.append(
                        {
                            "type": "exploration",
                            "title": title,
                            "description": f"Based on your interests, explore {item.topic}",
                            "confidence": float(getattr(self, "curiosity_level", 0.5)),
                        }
                    )

            except Exception:
                pass

            # ------------------------
            # 🎯 LIMIT RESULTS
            # ------------------------
            max_results = 5
            suggestions = suggestions[:max_results]

            # ------------------------
            # 📊 METRICS
            # ------------------------
            try:
                self.task_analyses = getattr(self, "task_analyses", 0) + 1
            except Exception:
                pass

            # ------------------------
            # 📢 LOG
            # ------------------------
            try:
                logger.debug(
                    f"🧠 Task analyzed: {task[:50]} ({len(suggestions)} suggestions)"
                )
            except Exception:
                pass

            return suggestions

        except Exception as e:
            try:
                logger.debug(f"Task analysis error: {e}")
            except Exception:
                pass

            return []

    # ------------------------
    # MAIN LOOP 🔥 (FIXED)
    # ------------------------
    async def run(self, interval: float = 5.0):
        """
        SAFE curiosity loop (ultra-stable + production-grade)
        """

        import asyncio
        import time

        try:
            # ------------------------
            # 🔁 ALREADY RUNNING CHECK
            # ------------------------
            if getattr(self, "_running", False):
                return

            self._running = True

            try:
                logger.info("🧠 Curiosity engine (PRODUCTION MODE) running")
            except Exception:
                pass

            last_run = 0
            COOLDOWN = 10

            # ------------------------
            # 🔄 MAIN LOOP
            # ------------------------
            while getattr(self, "_running", False):

                try:
                    now = time.time()

                    # ------------------------
                    # ❤️ HEARTBEAT
                    # ------------------------
                    self._last_heartbeat = now

                    # ------------------------
                    # 💤 IDLE CHECK (SAFE)
                    # ------------------------
                    try:
                        system = getattr(self, "system", None)
                        idle_controller = getattr(system, "idle_controller", None)

                        if idle_controller and hasattr(idle_controller, "is_idle"):
                            is_idle = idle_controller.is_idle
                            if callable(is_idle):
                                is_idle = is_idle()

                            if not is_idle:
                                await asyncio.sleep(2)
                                continue

                    except Exception:
                        pass

                    # ------------------------
                    # ⏱️ COOLDOWN CONTROL
                    # ------------------------
                    if now - last_run < COOLDOWN:
                        await asyncio.sleep(1.5)
                        continue

                    # ------------------------
                    # 🎲 RANDOM TRIGGER (LOW LOAD)
                    # ------------------------
                    if random.random() > 0.03:
                        await asyncio.sleep(interval)
                        continue

                    last_run = now

                    # ------------------------
                    # 🔥 GENERATE TASK (SAFE)
                    # ------------------------
                    try:
                        if not getattr(self, "queue", None):
                            await self.generate_curiosity()
                    except Exception:
                        pass

                    # ------------------------
                    # 🚀 EXECUTE SINGLE TASK (SAFE + TIMEOUT)
                    # ------------------------
                    queue = getattr(self, "queue", [])

                    if queue:
                        try:
                            item = queue.pop(0)

                            await asyncio.wait_for(self.explore(item), timeout=15)

                        except asyncio.TimeoutError:
                            try:
                                logger.warning("⏱️ Curiosity exploration timeout")
                            except Exception:
                                pass

                        except Exception:
                            pass

                    # ------------------------
                    # ⏳ SMART SLEEP (JITTER)
                    # ------------------------
                    sleep_time = interval + random.uniform(-0.5, 0.5)
                    await asyncio.sleep(max(1.0, sleep_time))

                except asyncio.CancelledError:
                    break

                except Exception as e:
                    try:
                        logger.error(f"Curiosity loop error: {e}")
                    except Exception:
                        pass

                    await asyncio.sleep(2)

        finally:
            # ------------------------
            # 🛑 CLEAN SHUTDOWN
            # ------------------------
            self._running = False

            try:
                logger.info("🛑 Curiosity engine stopped")
            except Exception:
                pass

