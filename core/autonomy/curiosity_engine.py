    # ------------------------
    async def explore(self, item: CuriosityItem) -> Dict[str, Any]:
        """
        Explore a curiosity topic safely (optimized + production-grade)
        """

        import time
        from datetime import datetime
        import asyncio

        try:
            # ------------------------
            # 🔥 VALIDATION
            # ------------------------
            if not item or not hasattr(item, "topic"):
                return {"error": "invalid_item"}

            topic = str(item.topic).strip()
            if not topic:
                return {"error": "invalid_topic"}

            # ------------------------
            # ⏱️ COOLDOWN (CRITICAL FIX)
            # ------------------------
            now = time.time()
            if now - getattr(self, "_last_exploration_time", 0) < getattr(
                self, "_exploration_cooldown", 0
            ):
                return {"status": "cooldown", "message": "Exploration on cooldown"}

            self._last_exploration_time = now

            # ------------------------
            # 🔁 DUPLICATE CHECK
            # ------------------------
            explored = getattr(self, "explored_topics", set())
            if topic.lower() in {t.lower() for t in explored}:
                return {"status": "already_explored", "topic": topic}

            # ------------------------
            # 📢 LOG
            # ------------------------
            try:
                logger.info(f"🔍 Exploring: {topic}")
            except Exception:
                pass

            # ------------------------
            # 🔥 RESEARCH WITH TIMEOUT
            # ------------------------
            try:
                researcher = self._ensure_researcher()
                if researcher:
                    research = await asyncio.wait_for(
                        researcher.research(topic), timeout=10
                    )
                else:
                    research = {"error": "researcher_unavailable", "topic": topic}
            except asyncio.TimeoutError:
                research = {"error": "research_timeout", "topic": topic}
            except Exception as e:
                research = {"error": str(e), "topic": topic}

            # ------------------------
            # 🔁 NORMALIZE RESULT
            # ------------------------
            if research is None:
                research = {}

            if not isinstance(research, dict):
                research = {"data": str(research)}

            result = {
                "topic": topic,
                "data": research,
                "type": getattr(item.curiosity_type, "value", "unknown"),
                "timestamp": datetime.now().isoformat(),
                "source": getattr(item, "source", "unknown"),
                "priority": getattr(item, "priority", 2),
            }

            # ------------------------
            # 🔥 UPDATE ITEM STATE
            # ------------------------
            try:
                item.explored = True
                item.result = result
            except Exception:
                pass

            # ------------------------
            # 📊 TRACKING
            # ------------------------
            try:
                self.explored_topics = getattr(self, "explored_topics", set())
                self.explored_topics.add(topic)

                self.learning_history = getattr(self, "learning_history", [])
                self.learning_history.append(result)

                # limit history
                if len(self.learning_history) > 500:
                    self.learning_history = self.learning_history[-500:]

                self.exploration_count = getattr(self, "exploration_count", 0) + 1
                self._insights_generated = getattr(self, "_insights_generated", 0) + 1
            except Exception:
                pass

            # ------------------------
            # 🧠 MEMORY STORE (SAFE)
            # ------------------------
            try:
                if getattr(self, "memory", None) and hasattr(self.memory, "store"):
                    await asyncio.wait_for(self.memory.store(result), timeout=2)
            except Exception:
                pass

            return result

        except Exception as e:
            try:
                logger.error(f"❌ Exploration failed: {e}")
            except Exception:
                pass

            return {"error": str(e), "topic": getattr(item, "topic", None)}

