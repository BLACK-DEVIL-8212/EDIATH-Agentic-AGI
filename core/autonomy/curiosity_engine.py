class CuriosityType(Enum):
    EXPLORATION = "exploration"
    LEARNING = "learning"
    VERIFICATION = "verification"
    EXPANSION = "expansion"
    SUGGESTION = "suggestion"
    OPTIMIZATION = "optimization"


class SuggestionPriority(Enum):
    HIGH = 1
    MEDIUM = 2
    LOW = 3


@dataclass
class CuriosityItem:
    topic: str
    source: str
    curiosity_type: CuriosityType
    priority: int = 2
    created_at: datetime = field(default_factory=datetime.now)
    explored: bool = False
    result: Optional[Dict[str, Any]] = None


@dataclass
class CuriositySuggestion:
    """Suggestion generated by curiosity engine"""

    suggestion_id: str = field(default_factory=lambda: str(uuid.uuid4()))
    title: str = ""
    description: str = ""
    suggestion_type: CuriosityType = CuriosityType.SUGGESTION
    priority: SuggestionPriority = SuggestionPriority.MEDIUM
    confidence: float = 0.5
    context: Dict[str, Any] = field(default_factory=dict)
    created_at: datetime = field(default_factory=datetime.now)
    expires_at: Optional[datetime] = None
    is_taken: bool = False
    feedback: Optional[str] = None
    tags: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "suggestion_id": self.suggestion_id,
            "title": self.title,
            "description": self.description,
            "type": self.suggestion_type.value,
            "priority": self.priority.value,
            "confidence": self.confidence,
            "context": self.context,
            "created_at": self.created_at.isoformat(),
            "expires_at": self.expires_at.isoformat() if self.expires_at else None,
            "is_taken": self.is_taken,
            "tags": self.tags,
        }


