    async def get_recommendations(self, limit: int = 5) -> List[Dict[str, Any]]:
        """
        Get curiosity recommendations safely (optimized + production-grade)
        """

        try:
            # ------------------------
            # 🔥 VALIDATION
            # ------------------------
            try:
                limit = int(limit)
                limit = max(1, min(limit, 20))  # clamp
            except Exception:
                limit = 5

            recommendations: List[Dict[str, Any]] = []

            # ------------------------
            # 🔁 DEDUP SET
            # ------------------------
            seen = set()

            # ------------------------
            # 🔥 QUEUE-BASED
            # ------------------------
            try:
                queue = getattr(self, "queue", [])

                for item in queue:
                    if len(recommendations) >= limit:
                        break

                    topic = getattr(item, "topic", None)
                    if not topic:
                        continue

                    topic_key = str(topic).lower()
                    if topic_key in seen:
                        continue

                    seen.add(topic_key)

                    recommendations.append(
                        {
                            "topic": topic,
                            "type": getattr(
                                getattr(item, "curiosity_type", None),
                                "value",
                                "unknown",
                            ),
                            "priority": getattr(item, "priority", 2),
                            "source": getattr(item, "source", "unknown"),
                        }
                    )

            except Exception:
                pass

            # ------------------------
            # 🔥 GENERIC FALLBACK
            # ------------------------
            if len(recommendations) < limit:
                generic_topics = [
                    "AI trends",
                    "productivity hacks",
                    "learning techniques",
                    "automation tools",
                    "focus improvement",
                ]

                explored = {t.lower() for t in getattr(self, "explored_topics", set())}

                for topic in generic_topics:
                    if len(recommendations) >= limit:
                        break

                    topic_key = topic.lower()

                    if topic_key in seen or topic_key in explored:
                        continue

                    seen.add(topic_key)

                    recommendations.append(
                        {
                            "topic": topic,
                            "type": "exploration",
                            "priority": 3,
                            "source": "system",
                        }
                    )

            # ------------------------
            # 📊 METRICS
            # ------------------------
            try:
                self.recommendations_generated = getattr(
                    self, "recommendations_generated", 0
                ) + len(recommendations)
            except Exception:
                pass

            # ------------------------
            # 📢 LOG
            # ------------------------
            try:
                logger.debug(f"📌 Generated {len(recommendations)} recommendations")
            except Exception:
                pass

            return recommendations

        except Exception as e:
            try:
                logger.error(f"❌ Recommendation generation failed: {e}")
            except Exception:
                pass

            return []

