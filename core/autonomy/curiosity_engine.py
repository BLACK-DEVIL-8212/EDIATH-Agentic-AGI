    # ------------------------
    # ADD TOPIC
    # ------------------------
    def add_curiosity(
        self,
        topic: str,
        source: str,
        ctype: CuriosityType = CuriosityType.EXPLORATION,
        priority: int = 2,
    ) -> None:
        """
        Add curiosity item safely (optimized + production-grade)
        """

        try:
            # ------------------------
            # 🔥 VALIDATION
            # ------------------------
            if not topic or not isinstance(topic, str):
                return

            topic = topic.strip()
            if not topic:
                return

            # normalize topic for deduplication
            topic_key = topic.lower()

            # ------------------------
            # 🔁 DUPLICATE CHECK (CRITICAL FIX)
            # ------------------------
            if topic_key in (
                t.lower() for t in getattr(self, "explored_topics", set())
            ):
                return

            if any(
                getattr(item, "topic", "").lower() == topic_key
                for item in getattr(self, "queue", [])
            ):
                return

            # ------------------------
            # 🔥 PRIORITY NORMALIZATION
            # ------------------------
            try:
                priority = int(priority)
                priority = max(1, min(5, priority))  # clamp 1–5
            except Exception:
                priority = 2

            # ------------------------
            # 🔥 SAFE ENUM HANDLING
            # ------------------------
            if not isinstance(ctype, CuriosityType):
                ctype = CuriosityType.EXPLORATION

            # ------------------------
            # 🔥 CREATE ITEM
            # ------------------------
            item = CuriosityItem(
                topic=topic,
                source=source or "unknown",
                curiosity_type=ctype,
                priority=priority,
            )

            # ------------------------
            # 🔥 INSERT (PRIORITY SORTED)
            # ------------------------
            self.queue.append(item)

            try:
                # keep queue sorted by priority (lower = higher priority)
                self.queue.sort(key=lambda x: getattr(x, "priority", 2))
            except Exception:
                pass

            # ------------------------
            # 📊 METRICS
            # ------------------------
            try:
                self._insights_generated = getattr(self, "_insights_generated", 0) + 1
            except Exception:
                pass

            # ------------------------
            # 📢 LOG
            # ------------------------
            try:
                logger.debug(f"➕ Added curiosity: {topic} (priority={priority})")
            except Exception:
                pass

        except Exception as e:
            try:
                logger.warning(f"⚠ Failed to add curiosity '{topic}': {e}")
            except Exception:
                pass

    # ------------------------
    # SUGGESTION GENERATION
    # ------------------------
    async def generate_suggestions(
        self, context: str, limit: int = 3
    ) -> List[CuriositySuggestion]:
        """
        Generate suggestions safely (optimized + production-grade)
        """

        import time
        from datetime import datetime

        suggestions: List[CuriositySuggestion] = []

        try:
            # ------------------------
            # 🔥 VALIDATION
            # ------------------------
            if not context or not isinstance(context, str):
                return []

            context = context.strip()
            if not context:
                return []

            now = time.time()

            # ------------------------
            # ⏱️ COOLDOWN (CRITICAL FIX)
            # ------------------------
            if now - getattr(self, "_last_suggestion_time", 0) < getattr(
                self, "_suggestion_cooldown", 0
            ):
                return []

            context_lower = context.lower()

            # ------------------------
            # 🔁 HELPER: ADD SAFE SUGGESTION
            # ------------------------
            def add_suggestion(s: CuriositySuggestion):
                if len(suggestions) >= limit:
                    return

                # deduplicate by title
                if any(existing.title == s.title for existing in suggestions):
                    return

                suggestions.append(s)

            # ------------------------
            # 🔥 PATTERN-BASED SUGGESTIONS
            # ------------------------
            if any(k in context_lower for k in ["code", "programming", "python"]):
                add_suggestion(
                    CuriositySuggestion(
                        title="Improve Code Quality",
                        description="Consider adding error handling, comments, or optimizing performance.",
                        suggestion_type=CuriosityType.OPTIMIZATION,
                        priority=SuggestionPriority.MEDIUM,
                        confidence=0.75,
                        tags=["coding", "optimization"],
                    )
                )

                add_suggestion(
                    CuriositySuggestion(
                        title="Learn Best Practices",
                        description="Explore coding best practices for your current programming language.",
                        suggestion_type=CuriosityType.LEARNING,
                        priority=SuggestionPriority.LOW,
                        confidence=0.65,
                        tags=["learning", "best_practices"],
                    )
                )

            if any(k in context_lower for k in ["research", "search", "find"]):
                add_suggestion(
                    CuriositySuggestion(
                        title="Deeper Research",
                        description="Would you like me to search for more comprehensive information?",
                        suggestion_type=CuriosityType.EXPANSION,
                        priority=SuggestionPriority.HIGH,
                        confidence=0.85,
                        tags=["research", "expansion"],
                    )
                )

            if any(k in context_lower for k in ["learn", "study"]):
                add_suggestion(
                    CuriositySuggestion(
                        title="Related Topics",
                        description=f"Explore topics related to '{context[:50]}' for deeper understanding.",
                        suggestion_type=CuriosityType.LEARNING,
                        priority=SuggestionPriority.MEDIUM,
                        confidence=0.7,
                        tags=["learning", "related_topics"],
                    )
                )

            if any(k in context_lower for k in ["analyze", "data"]):
                add_suggestion(
                    CuriositySuggestion(
                        title="Data Visualization",
                        description="Consider visualizing your data for better insights.",
                        suggestion_type=CuriosityType.OPTIMIZATION,
                        priority=SuggestionPriority.MEDIUM,
                        confidence=0.7,
                        tags=["data", "visualization"],
                    )
                )

            # ------------------------
            # 🧠 MEMORY-BASED SUGGESTIONS
            # ------------------------
            try:
                memory_suggestions = await self._generate_memory_based_suggestions()
                for s in memory_suggestions or []:
                    if isinstance(s, CuriositySuggestion):
                        add_suggestion(s)
            except Exception:
                pass

            # ------------------------
            # 🔥 QUEUE-BASED SUGGESTIONS
            # ------------------------
            if getattr(self, "queue", None):
                for item in self.queue[:limit]:
                    if len(suggestions) >= limit:
                        break

                    try:
                        add_suggestion(
                            CuriositySuggestion(
                                title=f"Explore: {item.topic[:50]}",
                                description=f"Based on your interests, explore {item.topic}.",
                                suggestion_type=getattr(
                                    item, "curiosity_type", CuriosityType.EXPLORATION
                                ),
                                priority=(
                                    SuggestionPriority(item.priority)
                                    if 1 <= item.priority <= 3
                                    else SuggestionPriority.MEDIUM
                                ),
                                confidence=float(getattr(self, "curiosity_level", 0.5)),
                                tags=[
                                    "exploration",
                                    getattr(item, "source", "unknown"),
                                ],
                            )
                        )
                    except Exception:
                        continue

            # ------------------------
            # 🔥 FINAL LIMIT
            # ------------------------
            suggestions = suggestions[:limit]

            # ------------------------
            # ⏳ EXPIRATION
            # ------------------------
            expires = datetime.now().replace(hour=23, minute=59, second=59)
            for s in suggestions:
                try:
                    s.expires_at = expires
                except Exception:
                    pass

            # ------------------------
            # 📊 METRICS
            # ------------------------
            self._last_suggestion_time = now
            self.suggestion_count = getattr(self, "suggestion_count", 0) + len(
                suggestions
            )
            self._insights_generated = getattr(self, "_insights_generated", 0) + len(
                suggestions
            )

            # ------------------------
            # 🔁 ACTIVE STORE (SAFE)
            # ------------------------
            try:
                self.active_suggestions = getattr(self, "active_suggestions", [])
                self.active_suggestions.extend(suggestions)
            except Exception:
                pass

            # ------------------------
            # 🧹 CLEANUP
            # ------------------------
            try:
                self._clean_expired_suggestions()
            except Exception:
                pass

            # ------------------------
            # 📢 LOG
            # ------------------------
            try:
                logger.info(f"Generated {len(suggestions)} suggestions")
            except Exception:
                pass

            return suggestions

        except Exception as e:
            try:
                logger.error(f"Suggestion generation failed: {e}")
            except Exception:
                pass

            return []

    async def _generate_memory_based_suggestions(self) -> List[CuriositySuggestion]:
        """
        Generate suggestions from memory safely (optimized + production-grade)
        """

        suggestions: List[CuriositySuggestion] = []

        try:
            # ------------------------
            # 🔥 VALIDATION
            # ------------------------
            memory = getattr(self, "memory", None)
            if not memory or not hasattr(memory, "get_recent"):
                return []

            # ------------------------
            # 🔥 FETCH MEMORY (SAFE)
            # ------------------------
            try:
                recent = await memory.get_recent(10)
            except Exception:
                return []

            if not recent or not isinstance(recent, list):
                return []

            # ------------------------
            # 🔁 ANALYZE PATTERNS
            # ------------------------
            topic_counts = {}

            for entry in recent:
                if not isinstance(entry, dict):
                    continue

                topic = entry.get("topic") or entry.get("type")
                if not topic or not isinstance(topic, str):
                    continue

                topic_key = topic.strip().lower()
                if not topic_key:
                    continue

                topic_counts[topic_key] = topic_counts.get(topic_key, 0) + 1

            if not topic_counts:
                return []

            # ------------------------
            # 🔥 SELECT BEST TOPIC (SMART FIX)
            # ------------------------
            sorted_topics = sorted(
                topic_counts.items(), key=lambda x: x[1], reverse=True
            )

            explored = {t.lower() for t in getattr(self, "explored_topics", set())}

            for topic, count in sorted_topics:

                if count < 3:
                    continue

                if topic in explored:
                    continue

                # ------------------------
                # 🔥 BUILD SUGGESTION
                # ------------------------
                try:
                    suggestion = CuriositySuggestion(
                        title=f"Deepen Knowledge: {topic.capitalize()}",
                        description=f"You've shown repeated interest in {topic}. Want to explore it deeper?",
                        suggestion_type=CuriosityType.EXPANSION,
                        priority=SuggestionPriority.MEDIUM,
                        confidence=min(0.9, 0.5 + (count * 0.1)),
                        tags=["memory_based", topic],
                    )

                    suggestions.append(suggestion)
                    break  # limit to one

                except Exception:
                    continue

            return suggestions

        except Exception as e:
            try:
                logger.debug(f"Memory-based suggestion error: {e}")
            except Exception:
                pass

            return []

    def _clean_expired_suggestions(self):
        """Remove expired suggestions"""
        now = datetime.now()
        self.active_suggestions = [
            s
            for s in self.active_suggestions
            if s.expires_at is None or s.expires_at > now
        ]

        # Also clean history (keep last 100)
        if len(self.suggestion_history) > 100:
            self.suggestion_history = self.suggestion_history[-100:]

    async def get_suggestions_for_task(
        self, task: str, limit: int = 3
    ) -> List[CuriositySuggestion]:
        """Get suggestions specifically for a task"""
        return await self.generate_suggestions(task, limit)

    async def take_suggestion(
        self, suggestion_id: str, feedback: Optional[str] = None
    ) -> bool:
        """
        Mark a suggestion as taken safely (optimized + production-grade)
        """

        from datetime import datetime

        try:
            # ------------------------
            # 🔥 VALIDATION
            # ------------------------
            if not suggestion_id or not isinstance(suggestion_id, str):
                return False

            suggestions = getattr(self, "active_suggestions", [])
            if not suggestions:
                return False

            # ------------------------
            # 🔍 FIND SUGGESTION (SAFE)
            # ------------------------
            target = None
            for suggestion in suggestions:
                if getattr(suggestion, "suggestion_id", None) == suggestion_id:
                    target = suggestion
                    break

            if not target:
                return False

            # ------------------------
            # 🔥 UPDATE STATE
            # ------------------------
            try:
                target.is_taken = True
                target.feedback = feedback
                target.taken_at = datetime.now().isoformat()
            except Exception:
                pass

            # ------------------------
            # 🔁 SAFE REMOVE (CRITICAL FIX)
            # ------------------------
            try:
                self.active_suggestions = [
                    s
                    for s in suggestions
                    if getattr(s, "suggestion_id", None) != suggestion_id
                ]
            except Exception:
                pass

            # ------------------------
            # 📦 HISTORY STORE
            # ------------------------
            try:
                self.suggestion_history = getattr(self, "suggestion_history", [])
                self.suggestion_history.append(target)
            except Exception:
                pass

            # ------------------------
            # 🧠 LEARNING HISTORY
            # ------------------------
            try:
                self.learning_history = getattr(self, "learning_history", [])
                self.learning_history.append(
                    {
                        "type": "suggestion_taken",
                        "suggestion_id": suggestion_id,
                        "title": getattr(target, "title", None),
                        "feedback": feedback,
                        "timestamp": datetime.now().isoformat(),
                    }
                )
            except Exception:
                pass

            # ------------------------
            # 📊 METRICS
            # ------------------------
            try:
                self.taken_suggestions = getattr(self, "taken_suggestions", 0) + 1
            except Exception:
                pass

            # ------------------------
            # 📢 LOG
            # ------------------------
            try:
                logger.info(
                    f"✅ Suggestion taken: {getattr(target, 'title', suggestion_id)}"
                )
            except Exception:
                pass

            return True

        except Exception as e:
            try:
                logger.error(f"❌ Failed to take suggestion: {e}")
            except Exception:
                pass

            return False

